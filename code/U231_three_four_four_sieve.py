#!/usr/bin/env python3
"""U231 / Milestone 74: Diophantine Sieve and Adversarial Search for Signature (3, 4, 4).

Tests x^3 + y^4 = z^4 with x, y, z >= 1.
Beal's conjecture requires that any solution has gcd(x, y, z) > 1.
Equivalently, no primitive solutions (gcd(x, y, z) = 1) exist.

Includes:
1. Exact positive controls on known non-primitive solutions generated by
   difference-of-fourth-powers parametrization:
   - Positive Control 1: (3375, 225, 450) with gcd = 225
   - Positive Control 2: (512000, 6400, 19200) with gcd = 6400
2. Residue pre-filters modulo 7, 9, 13 for cube testing.
3. Exhaustive search over all coprime pairs 1 <= y < z <= 2000.
"""
from __future__ import annotations
import math
import sys
import time

CUBES_MOD7 = {0, 1, 6}
CUBES_MOD9 = {0, 1, 8}
CUBES_MOD13 = {0, 1, 5, 8, 12}

def exact_is_cube(n: int) -> int | None:
    """Return integer cube root if n is an exact cube, else None."""
    if n <= 0:
        return None
    r = int(round(n ** (1 / 3)))
    for test_r in (r - 1, r, r + 1):
        if test_r > 0 and test_r ** 3 == n:
            return test_r
    return None

def verify_positive_controls() -> None:
    # Control 1: 3375^3 + 225^4 == 450^4
    x1, y1, z1 = 3375, 225, 450
    assert x1 ** 3 + y1 ** 4 == z1 ** 4, "Control 1 arithmetic failure"
    g1 = math.gcd(math.gcd(x1, y1), z1)
    assert g1 == 225, f"Control 1 gcd mismatch: {g1}"
    assert g1 > 1, "Control 1 must have common factor > 1"

    # Control 2: 512000^3 + 6400^4 == 19200^4
    x2, y2, z2 = 512000, 6400, 19200
    assert x2 ** 3 + y2 ** 4 == z2 ** 4, "Control 2 arithmetic failure"
    g2 = math.gcd(math.gcd(x2, y2), z2)
    assert g2 == 6400, f"Control 2 gcd mismatch: {g2}"
    assert g2 > 1, "Control 2 must have common factor > 1"

def run_sieve(max_z: int = 2000) -> tuple[int, int]:
    pairs_tested = 0
    primitive_solutions = []

    # Iterate over z and y
    for z in range(2, max_z + 1):
        z4 = z ** 4
        z2 = z ** 2
        for y in range(1, z):
            if math.gcd(y, z) != 1:
                continue
            pairs_tested += 1

            # D = z^4 - y^4 = (z^2 - y^2)(z^2 + y^2)
            y2 = y ** 2
            D = (z2 - y2) * (z2 + y2)

            # Modulo pre-filters
            if (D % 7) not in CUBES_MOD7:
                continue
            if (D % 9) not in CUBES_MOD9:
                continue
            if (D % 13) not in CUBES_MOD13:
                continue

            # Exact cube test
            x = exact_is_cube(D)
            if x is not None:
                g = math.gcd(math.gcd(x, y), z)
                if g == 1:
                    primitive_solutions.append((x, y, z))

    return pairs_tested, len(primitive_solutions)

def main() -> int:
    t0 = time.perf_counter()
    print("=== Milestone 74: Signature (3, 4, 4) Diophantine Sieve ===")
    print("Testing positive controls...")
    verify_positive_controls()
    print("  [PASS] Control 1: 3375^3 + 225^4 = 450^4 (gcd = 225 > 1)")
    print("  [PASS] Control 2: 512000^3 + 6400^4 = 19200^4 (gcd = 6400 > 1)")

    max_z = 2000
    print(f"Running exhaustive search for coprime pairs 1 <= y < z <= {max_z}...")
    pairs, prim = run_sieve(max_z)
    elapsed = time.perf_counter() - t0

    print(f"  Coprime pairs checked: {pairs:,}")
    print(f"  Primitive solutions found: {prim}")
    print(f"  Elapsed time: {elapsed:.2f}s")

    if prim != 0:
        print(f"FAILED: Found {prim} primitive solutions (Beal counterexample)!")
        return 1

    print("ALL TESTS PASSED: 0 primitive solutions found in search box.")
    print("Signature (3, 4, 4) primitive non-existence verified consistent with Lean Beal.ThreeFourFour.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
