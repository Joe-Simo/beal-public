"""Drill into the top-ranked direction with Jev: generate many CONCRETE p-adic claims about a
Beal counterexample, rank them, then test the best ones exactly.

Each claim is a specific, falsifiable statement -- not a research direction -- so Jev is being
asked the narrow kind of question it answers well, and every survivor gets an exact test.
"""
from __future__ import annotations
import itertools, json, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import jev

CLAIMS = [
 "Exactly one of A, B, C is divisible by 3.",
 "If 3 divides none of A, B, C then A^x + B^y = C^z is impossible mod 9.",
 "The even one among A, B, C has 2-adic valuation at least 2.",
 "If C is even then v_2(C^z) >= 3, so A^x + B^y = 0 mod 8.",
 "If C is even then A^x + B^y = 0 mod 8 forces A = B mod 4 or A = -B mod 4.",
 "For every prime p dividing C, the order of A modulo p divides a proper divisor of p-1.",
 "For every prime p dividing C we have A^x = -B^y mod p^(z v_p(C)), a congruence to a power at least p^3.",
 "No prime p can divide both A and x.",
 "If p divides C and p = 1 mod x then x divides p - 1 constrains the residue of A.",
 "The exponent z is odd whenever C is even.",
 "If A is even then v_2(A^x) = x v_2(A) >= 3, so B^y = C^z mod 8.",
 "If A is even then B^y = C^z mod 8 forces B = C mod 8 or B^y and C^z are both 1 mod 8.",
 "For odd A, A^x = A mod 8 whenever x is odd, so the parity of x is visible mod 8.",
 "Every odd square is 1 mod 8, so if any exponent is even the corresponding term is 1 mod 8.",
 "If all three exponents are odd primes then A^x = A, B^y = B, C^z = C mod 2.",
 "If x, y, z are all odd then A + B = C mod 2, which is automatic and gives nothing.",
 "The three bases cannot all be 1 mod 4.",
 "If A, B are both odd then C is even and C^z = A^x + B^y = 2 mod 4 when A = B mod 4.",
 "If A, B are both odd and A = B mod 4 then v_2(C^z) = 1, forcing z = 1, a contradiction.",
 "If A, B are both odd and A = -B mod 4 then v_2(A^x + B^y) >= 2.",
 "For p an odd prime dividing C, A^x = -B^y mod p means -B^y A^(-x) = 1, so -1 is in the group generated by A and B mod p.",
 "If C is even then A and B are both odd and A^x + B^y = 0 mod 2^z with z >= 3.",
 "If C is even and x, y are both odd then A + B = 0 mod 8 is forced.",
 "The product ABC is divisible by 6.",
 "At least one of A, B, C is divisible by 3.",
]

CONTEXT = (
 "Beal counterexample: A^x+B^y=C^z, A,B,C >= 1, x,y,z >= 3, gcd(gcd(A,B),C)=1. KERNEL-VERIFIED "
 "here: the bases are PAIRWISE coprime; A != B; EXACTLY ONE of A,B,C is even; B^y < C^z <= 2B^y "
 "when A^x <= B^y; every signature has |chi| >= 1/12. Judge each claim as a mathematical "
 "statement about such a counterexample."
)

Q = {
 "likely_true": jev.score(
   "Is this claim TRUE of every Beal counterexample? Judge the exact statement. Watch for claims "
   "that are true only under an extra hypothesis, that confuse a base with a term, or that are "
   "vacuous.",
   ["level 0: the claim is false, or a counterexample to it is easy to construct",
    "level 1: the claim is true only under an extra hypothesis not stated",
    "level 2: the claim is probably true but the argument is not immediate",
    "level 3: the claim is true and follows directly from the verified facts listed"]),
 "decisive": jev.score(
   "If this claim were established, how much would it constrain a hypothetical counterexample?",
   ["level 0: vacuous, or already implied by the verified facts listed",
    "level 1: a mild restriction on residues",
    "level 2: a genuine new necessary condition",
    "level 3: it would force a contradiction, or exclude an infinite family"]),
 "exactly_testable": jev.noul(
   "Can this claim be settled by exact finite computation or a short elementary derivation?",
   true="a bounded exact computation or a few lines of elementary number theory settles it",
   false="settling it needs a deep theorem or an unbounded search"),
}

states=[{"context":CONTEXT,"claim":c} for c in CLAIMS]
rs=jev.ask_many(states,Q,concurrency=12)
rows=[]
for c,st,r in zip(CLAIMS,states,rs):
    if "error" in r: continue
    jev.persist("padic_claim", st, Q, r)
    a=r["answers"]
    rows.append((round(a["likely_true"]["score"],2), round(a["decisive"]["score"],2),
                 round(a["exactly_testable"]["noul"],2), c))
rows.sort(key=lambda t:-(t[0]*t[1]*t[2]))
print(f"{'true':>6}{'decisive':>10}{'testable':>10}  claim")
for t in rows[:14]:
    print(f"{t[0]:>6}{t[1]:>10}{t[2]:>10}  {t[3][:86]}")
print(f"\nranked {len(rows)} concrete p-adic claims")
